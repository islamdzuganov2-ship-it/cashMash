QA_SCHEMA = """\
{
  "answer": "ответ по существу, или пусто если ответить нечем",
  "fact_ids": ["..."],
  "refused": true | false,
  "refusal_reason": "чего не хватает в данных; пусто если refused=false"
}\
"""

QA_SYSTEM = SYSTEM + """
Дополнительно для режима вопроса и ответа: если в ФАКТАХ нет данных,
чтобы ответить, ставь refused=true и объясняй, чего именно не хватает.
Ответ наугад хуже отказа — отказ можно исправить, сбор данных, а
выдумку замечают через месяц и через чужие деньги.
"""


def build_qa(sheet: FactSheet, context: list[tuple[Chunk, float]],
             question: str, limit: int = 0) -> tuple[str, str, list[str]]:
    if limit:
        facts_block, shown = select_facts(sheet, "", question,
                                          int(limit * 0.7))
        ctx_block = render_context(context, limit - len(facts_block))
    else:
        facts_block = sheet.render()
        shown = sheet.ids()
        ctx_block = render_context(context)
    user = f"""\
ФАКТЫ (единственный источник чисел):
{facts_block}

ВЫДЕРЖКИ:
{ctx_block}

ВОПРОС:
{question}

Ответь объектом JSON строго по схеме:
{QA_SCHEMA}
"""
    return QA_SYSTEM, user, shown
