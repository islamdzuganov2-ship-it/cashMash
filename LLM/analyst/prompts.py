# --- укладка в окно модели ------------------------------------------------

# Русский текст дороже английского в токенах: кириллица режется на
# куски по два-три символа. Делитель занижен намеренно — ошибиться в
# большую сторону значит получить отказ сервера вместо ответа.
CHARS_PER_TOKEN = 2.4

# Факты, которые нужны почти всегда: на них держится любой разбор, и
# выбрасывать их ради подробностей по часам бессмысленно.
CORE = ("trades.count", "trades.net_bps_avg", "trades.win_rate",
        "trades.gross_bps_avg", "trades.fee_bps_avg", "geometry.",
        "attrib.", "drawdown.depth_bps", "exec.", "trader.mode")


def budget_chars(n_ctx: int, max_tokens: int, overhead: int = 1200) -> int:
    """Сколько символов можно отдать под факты и выдержки.

    Из окна вычитается ответ и запас на служебную разметку. Остаток —
    не «рекомендация», а жёсткий потолок: подсказка длиннее окна не
    обрезается сервером, а отвергается целиком."""
    room = max(512, n_ctx - max_tokens - overhead)
    return int(room * CHARS_PER_TOKEN)


def _fact_line(f) -> str:
    return (f"[{f.id}] {f.label}: {f.text()}"
            + (f" — {f.note}" if f.note else ""))


def select_facts(sheet: FactSheet, spec: str, query: str,
                 limit: int) -> tuple[str, list[str]]:
    """Отобрать факты под задачу и уложить в отведённые символы.

    Порядок отбора: сначала опорные, потом совпавшие с вопросом по
    словам, потом всё остальное. Обрезается хвост, а не середина: в
    хвосте лежат подробности разрезов, без которых разбор беднеет, но
    остаётся верным. Без опорных он перестаёт быть верным.

    Возвращает и текст, и перечень показанных фактов. Второе нужно
    контролю: чтобы отличить ошибку ссылки от выдумки, надо знать, что
    модель вообще видела. Число из факта, которого ей не показывали,
    она знать не могла — совпадение там случайно, и принимать его за
    источник нельзя."""
    from .index import tokens

    prefixes = [p.strip() for p in spec.split(",") if p.strip()]
    pool = [f for f in sheet
            if not prefixes or any(f.id.startswith(p) for p in prefixes)]
    words = set(tokens(query)) if query else set()

    def rank(f) -> tuple[int, float]:
        if any(f.id.startswith(c) for c in CORE):
            return (0, 0.0)
        hit = len(words & set(tokens(f"{f.id} {f.label} {f.note}")))
        return (1 if hit else 2, -hit)

    out: list[str] = []
    shown: list[str] = []
    used = 0
    dropped = 0
    for f in sorted(pool, key=rank):
        line = _fact_line(f)
        if used + len(line) + 1 > limit:
            dropped += 1
            continue
        out.append(line)
        shown.append(f.id)
        used += len(line) + 1
    if dropped:
        out.append(f"(ещё {dropped} фактов не поместились в окно модели; "
                   f"на них ссылаться нельзя)")
    return "\n".join(out), shown


def render_facts(sheet: FactSheet, spec: str) -> str:
    """Отобрать факты под задачу. Пустая строка — подать все."""
    prefixes = [p.strip() for p in spec.split(",") if p.strip()]
    return sheet.render(prefixes or None)


def render_context(chunks: list[tuple[Chunk, float]],
                   limit: int = 1_000_000) -> str:
    """Выдержки, уложенные в отведённые символы.

    Выдержки урезаются раньше фактов и по той же причине: выдержка
    объясняет, факт доказывает. Разбор без половины документации
    беднее; разбор без половины чисел — неверен."""
    if not chunks:
        return "(выдержек нет)"
    out: list[str] = []
    used = 0
    for ch, _ in chunks:
        piece = f"--- {ch.cite()}\n{ch.text.strip()}"
        if used + len(piece) > limit:
            if not out:                      # хотя бы одна, пусть куском
                out.append(piece[:limit])
            break
        out.append(piece)
        used += len(piece) + 2
    return "\n\n".join(out) if out else "(выдержек нет)"


def build(task: str, sheet: FactSheet,
          context: list[tuple[Chunk, float]],
          extra_question: str = "",
          limit: int = 0) -> tuple[str, str, list[str]]:
    """Собрать «системная подсказка, запрос, показанные факты»."""
    spec = TASKS.get(task, {})
    question = extra_question or spec.get("question", "")
    if limit:
        # Две трети под факты, треть под выдержки.
        facts_block, shown = select_facts(
            sheet, spec.get("facts", ""),
            question + " " + spec.get("query", ""), int(limit * 0.65))
        ctx_block = render_context(context, limit - len(facts_block))
    else:
        prefixes = [p.strip() for p in spec.get("facts", "").split(",")
                    if p.strip()]
        facts_block = render_facts(sheet, spec.get("facts", ""))
        shown = [f.id for f in sheet
                 if not prefixes or any(f.id.startswith(p) for p in prefixes)]
        ctx_block = render_context(context)
    user = f"""\
ФАКТЫ (единственный источник чисел; идентификатор в квадратных скобках):
{facts_block}

ВЫДЕРЖКИ (техническое задание, код робота, подтверждённые ранее
закономерности, карточки сделок — источник объяснений, не чисел):
{ctx_block}

ЗАДАЧА:
{question}

Ответь объектом JSON строго по схеме:
{SCHEMA}
"""
    return SYSTEM, user, shown


