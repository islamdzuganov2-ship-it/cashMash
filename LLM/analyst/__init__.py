"""Аналитик CashMash — разбор работы робота локальной языковой моделью.

Робот торгует сам. Эта подсистема его не трогает: она читает то, что он
оставил после себя, и объясняет, почему получилось так, а не иначе.

Разделение обязанностей здесь жёсткое и оно же главное:

    числа считает Python,  формулирует выводы модель.

Модель не умеет считать и не должна — она умеет связывать. Поэтому все
величины до единой вычисляются в `facts.py` и подаются модели готовым
списком, а `guard.py` потом проверяет, что в тексте не появилось ни
одного числа, которого не было в этом списке. Число без источника —
не «мелкая неточность», а ровно тот случай, ради которого всё и
затевалось: вывод, сделанный из выдуманного факта, неотличим по виду
от настоящего и опаснее молчания.
"""

